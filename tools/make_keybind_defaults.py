"""Generates src/game/keybind_defaults.py from the default presets shipped with Elite Dangerous.

Usage: python tools/make_keybind_defaults.py [preset files]

Without arguments the presets in assets/keybind_presets/ are used, in the order keyboard and mouse, keyboard only,
controller (the first one that has a key for an action wins).

The result only holds the keys for the actions EDAP needs and which other actions share a key with them in the
defaults (Elite allows that). Keys are stored under their US names, so they do not depend on the keyboard layout
of the preset files.
"""

import subprocess
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from controls.directinput import SCANCODE, scancode_for  # noqa: E402
from game.keybind_spec import REQUIRED_ACTIONS  # noqa: E402

US_NAMES = {code: name for name, code in reversed(list(SCANCODE.items())) if not name.startswith("??")}


def keyboard_combos(item, layout):
    """The (key, modifiers) of all keyboard slots of an action, as US key names."""
    combos = []
    for slot in item:
        if slot.tag not in ("Primary", "Secondary") or slot.attrib.get("Device", "").strip() != "Keyboard":
            continue
        try:
            key = US_NAMES[scancode_for(slot.attrib["Key"], layout)]
            mods = tuple(sorted(US_NAMES[scancode_for(m.attrib["Key"], layout)] for m in slot.findall("Modifier")))
        except KeyError:
            continue
        combos.append((key, mods))
    return combos


def main(paths):
    defaults = {name: [] for name in REQUIRED_ACTIONS}
    shared = {name: set() for name in REQUIRED_ACTIONS}
    for path in paths:
        root = ET.parse(path).getroot()
        layout = root.findtext("KeyboardLayout")
        by_combo = {}
        for item in root:
            for combo in keyboard_combos(item, layout):
                by_combo.setdefault(combo, set()).add(item.tag)
        for name in REQUIRED_ACTIONS:
            item = root.find(name)
            if item is None:
                continue
            for combo in keyboard_combos(item, layout):
                if combo not in defaults[name]:
                    defaults[name].append(combo)
                shared[name] |= by_combo[combo] - {name}

    lines = [
        '"""Generated by tools/make_keybind_defaults.py from the default Elite Dangerous presets. Do not edit."""',
        "",
        "# Keyboard keys of the default presets (keyboard and mouse, keyboard only, controller) as (key, modifiers) with US",
        "# key names. The first line of each action is the one tried first.",
        "DEFAULT_KEYS: dict[str, tuple[tuple[str, tuple[str, ...]], ...]] = {",
    ]
    for name in REQUIRED_ACTIONS:
        lines.append(f"    {name!r}: {tuple(defaults[name])!r},")
    lines += [
        "}",
        "",
        "# Other actions that share a key with an EDAP action in the default presets, so Elite accepts that.",
        "SHARED_IN_DEFAULTS: dict[str, frozenset[str]] = {",
    ]
    for name in REQUIRED_ACTIONS:
        lines.append(f"    {name!r}: frozenset({sorted(shared[name])!r}),")
    lines += ["}", ""]
    target = ROOT / "src" / "game" / "keybind_defaults.py"
    target.write_text("\n".join(lines), encoding="utf-8")
    subprocess.run([sys.executable, "-m", "ruff", "format", str(target)], check=False)
    print(f"Wrote {target}")


if __name__ == "__main__":
    presets = ROOT / "assets" / "keybind_presets"
    main(sys.argv[1:] or [presets / f"{name}.4.2.binds" for name in ("KeyboardAndMouse", "Keyboard", "Controller")])
